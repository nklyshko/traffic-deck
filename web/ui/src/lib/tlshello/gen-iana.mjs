// Regenerates iana.ts from the IANA registries: `node gen-iana.mjs` (Node 18+).
import { writeFileSync } from 'node:fs'

const BASE = 'https://www.iana.org/assignments/'
const REGISTRIES = [
  ['CIPHER_SUITES', 'tls-parameters/tls-parameters-4.csv', 'TLS Cipher Suites'],
  ['EXTENSIONS', 'tls-extensiontype-values/tls-extensiontype-values-1.csv', 'TLS ExtensionType Values'],
  ['GROUPS', 'tls-parameters/tls-parameters-8.csv', 'TLS Supported Groups'],
  ['SIGNATURE_SCHEMES', 'tls-parameters/tls-signaturescheme.csv', 'TLS SignatureScheme'],
  ['EC_POINT_FORMATS', 'tls-parameters/tls-parameters-9.csv', 'TLS EC Point Format'],
  ['CERTIFICATE_TYPES', 'tls-extensiontype-values/tls-extensiontype-values-3.csv', 'TLS Certificate Types'],
  ['QUIC_PARAMETERS', 'quic/quic-transport.csv', 'QUIC Transport Parameters'],
]

function rows(csv) {
  const out = []
  let row = [], field = '', quoted = false
  for (let i = 0; i < csv.length; i++) {
    const c = csv[i]
    if (quoted) {
      if (c === '"' && csv[i + 1] === '"') { field += '"'; i++ }
      else if (c === '"') quoted = false
      else field += c
    } else if (c === '"') quoted = true
    else if (c === ',') { row.push(field); field = '' }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && csv[i + 1] === '\n') i++
      row.push(field); out.push(row); row = []; field = ''
    } else field += c
  }
  if (field || row.length) { row.push(field); out.push(row) }
  return out.slice(1)
}

// "0x13,0x01" (cipher suites), "0x0403", "29"; null for a range such as "0x00,0x5D-5F".
function value(v) {
  if (v.includes('-') || v.includes('*')) return null
  const parts = v.split(',').map((p) => p.trim())
  if (parts.length === 2) return (Number(parts[0]) << 8) | Number(parts[1])
  return /^0x/i.test(parts[0]) ? BigInt(parts[0]) : Number(parts[0])
}

let out = `// Generated by gen-iana.mjs from the IANA registries on ${new Date().toISOString().slice(0, 10)}. Do not edit.\n`
for (const [name, path, title] of REGISTRIES) {
  const res = await fetch(BASE + path)
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`)
  const entries = []
  for (const [v, desc] of rows(await res.text())) {
    if (!v || !desc || /^(Unassigned|Reserved)/i.test(desc)) continue
    const n = value(v)
    if (n === null) continue
    // QUIC parameter ids run to 62 bits, so that table is keyed by the hex string.
    const key = name === 'QUIC_PARAMETERS' ? `'0x${n.toString(16)}'` : `0x${Number(n).toString(16).padStart(name === 'EC_POINT_FORMATS' || name === 'CERTIFICATE_TYPES' ? 2 : 4, '0')}`
    // Registry notes such as '(renamed from "elliptic_curves")' are history, not the name.
    entries.push(`  ${key}: ${JSON.stringify(desc.replace(/\s*\(renamed from[^)]*\)/, '').trim())},`)
  }
  out += `\n// ${title}: ${BASE}${path.replace(/-\d+\.csv$|\.csv$/, '')}\nexport const ${name}: Record<${name === 'QUIC_PARAMETERS' ? 'string' : 'number'}, string> = {\n${entries.join('\n')}\n}\n`
}
writeFileSync(new URL('./iana.ts', import.meta.url), out)
